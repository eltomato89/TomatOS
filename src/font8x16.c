/* TomatOS - the 8x16 bitmap font the framebuffer console renders with
*  Desc: 256 glyphs, one per CP437 code point, sixteen bytes each. A byte is
*        one row of the glyph, top row first, and the most significant bit is
*        the leftmost pixel -- so 0x80 lights only the left edge and 0x01 only
*        the right. fbcon.c walks the sixteen bytes and plots a pixel wherever
*        a bit is set.
*
*  Why 8x16 and not the 8x8 of font8x8.c. At 1024x768 an 8x8 cell gives
*  128x96 characters, which on a real display is too small to read. An 8x16
*  cell gives 128x48 -- still far more room than the 80x25 of text mode, and
*  comfortable at arm's length.
*
*  Why 256 glyphs and not 128. The console translates what it prints to
*  CP437, and the kernel already relies on that: it draws its status bar dots
*  with 0xFE and the sharp s with 0xE1. Stopping at 0x7F would paint those,
*  every box drawing character and every accented letter as a blank cell,
*  which does not look like a missing glyph -- it looks like a broken
*  console.
*
*  The cell is eight pixels wide and sixteen tall. Glyphs are drawn seven
*  pixels wide in columns 0..6, which leaves column 7 blank so that
*  neighbouring characters do not touch; M, W and a few others borrow column
*  7 as well, as they must to stay in proportion. Strokes are two pixels
*  wide, which is what makes the face readable rather than spidery at this
*  size. The vertical metrics are:
*
*      rows 0,1     clear, and where the accent of a capital goes
*      row  2       top of an ascender (b d f h k l) and of a lower case
*                   accent
*      row  3       cap height
*      row  6       x-height
*      row  11      baseline -- the last row of a letter with no descender
*      rows 12..14  descenders of g j p q y, the tail of Q, the comma and
*                   the semicolon, the cedilla of C and c
*      row  15      clear
*
*  Lower case therefore sits on the baseline with real descenders rather
*  than being small capitals, and the pairs that get confused are drawn
*  apart on purpose: I has serifs top and bottom, l only a top left one and
*  1 a flag and a wide foot; 0 carries a diagonal that O does not; 5 has a
*  flat top bar where S has a curve; 2 has a curved top where Z has a bar;
*  6 has a closed bowl where G has a crossbar and a spur; c is open on the
*  right where o is closed; B has a straight left stem where 8 is round.
*
*  The underscore fills the full width of rows 13 and 14 so that a run of
*  them forms an unbroken rule, and the vertical bar fills all sixteen rows
*  so that stacked bars draw a continuous line.
*
*  Codes 0x00..0x1F carry the CP437 graphics -- the faces, the card suits,
*  the arrows -- rather than being blank. The console acts on the control
*  codes it cares about long before anything reaches the font, so nothing
*  ever asks this table to draw a carriage return; what it does ask for is
*  what CP437 says lives at those codes, and a program that wants an arrow
*  or a musical note should get one. 0x00 is blank because a run off the end
*  of a string should not paint anything, and so is 0xFF, which is CP437's
*  no-break space. 0x7F is the CP437 house, not a replacement box.
*
*  Each glyph carries a picture of itself in the comment above it. The
*  picture is the authority: if a character comes out wrong on screen, fix
*  the picture and make the bytes agree with it, column by column -- a set
*  bit is a '#', reading left to right from bit 7 down to bit 0. Every glyph
*  in this file was checked by rendering the whole table back out as text
*  and reading it, which is the only way to find a byte that is plausible
*  but wrong; nothing here was transcribed from memory and left unseen.
*
*  The box drawing set, 0xB0..0xDF, was not drawn by eye at all. What
*  matters about it is a property no eye can check one glyph at a time: two
*  cells side by side, or one above the other, must join without a step or a
*  gap. So those glyphs were generated from a description of their four arms
*  -- up, down, left and right, each absent, single or double -- by code
*  that lays every stroke on the same rows and columns in every glyph. A
*  single stroke is two pixels wide and runs down columns 3,4 or across rows
*  7,8; a double stroke is two rails, columns 1,2 and 5,6 or rows 5,6 and
*  9,10. Where a double branch opens into a double line the wall it opens
*  through is broken over the width of the gap, which is what makes the
*  inside of ╔, ╠ and ╬ hollow the way it should be.
*
*  Every entry is written with its index spelled out, [0x41] = { ... }, so a
*  glyph is nailed to its character code. Inserting or deleting a line can
*  then never slide the rest of the table along by one, which is the failure
*  that would otherwise turn every character after the mistake into its
*  neighbour, and a code initialised twice is caught by -Woverride-init,
*  which -Wextra turns on.
*
*  The outer bound is deliberately left empty. With [256] written in, a
*  sizeof check proves nothing at all: the compiler pads the array out to
*  256 entries whatever the initialiser contains, so a table that stopped at
*  0xC0 would pass. Left empty, the bound is whatever the initialiser
*  actually reaches, and the check below then does catch a table that stops
*  short or one that overruns. It cannot catch a hole in the middle -- that
*  is what the spelled out indices and the picture above each entry are for.
*/
