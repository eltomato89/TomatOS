/* TomatOS - the 8x8 bitmap font used by the mode 13h text routines
*  Desc: 128 glyphs, one per ASCII code, eight bytes each. A byte is one
*        row of the glyph, top row first, and the most significant bit is
*        the leftmost pixel -- so 0x80 lights only the left edge and 0x01
*        only the right. vga_char() walks the eight bytes and plots a pixel
*        wherever a bit is set.
*
*  The cell is eight pixels square. Glyphs are drawn six pixels wide in
*  columns 1..6, which leaves a blank column on either side so that
*  neighbouring characters do not touch; the few naturally wide ones (M, W,
*  m, w, # and &) borrow column 0 as well. Capitals occupy rows 0..6 and sit
*  on a baseline at row 6, lower case letters keep to rows 2..6 so that they
*  read as lower case rather than as small capitals, and row 7 is left free
*  for the descenders of g, j, p, q, y, the comma, the semicolon and the tail
*  of Q. The underscore fills row 7 across the whole cell so that a run of
*  them forms an unbroken rule, and the vertical bar fills all eight rows so
*  that stacked bars draw a continuous line.
*
*  Codes 0x00..0x1F are blank: the console interprets the control codes it
*  cares about before it ever reaches the font, and a blank cell is the least
*  disruptive thing to paint for the rest. 0x7F is a hollow box, which makes
*  an accidental attempt to draw an undrawable code visible instead of silent.
*
*  Each glyph carries a picture of itself in the comment above it. The
*  picture is the authority: if a character comes out wrong on screen, fix
*  the picture and make the bytes agree with it, column by column -- a set
*  bit is a '#', reading left to right from bit 7 down to bit 0.
*
*  Every entry is written with its index spelled out, [0x41] = { ... }, so a
*  glyph is nailed to its character code. Inserting or deleting a line can
*  then never slide the rest of the table along by one, which is the failure
*  that would otherwise turn every character after the mistake into its
*  neighbour, and a code initialised twice is caught by -Woverride-init,
*  which -Wextra turns on.
*/
