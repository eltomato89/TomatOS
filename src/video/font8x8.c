/* Compile time check that the table really is 128 glyphs of FONT_HEIGHT
*  bytes: vgadraw.c indexes it with a raw character value and would run off
*  the end of a short table. A negative array size is a hard error, so this
*  cannot be ignored. */
typedef char font8x8_size_check[
    (sizeof(font8x8) == 128 * FONT_HEIGHT) ? 1 : -1];
typedef char font8x8_glyph_size_check[
    (sizeof(font8x8[0]) == FONT_HEIGHT) ? 1 : -1];
